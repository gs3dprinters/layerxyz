export function getCategories(): Category[] {
  return CATEGORIES;
}

export function getCategoryBySlug(slug: string): Category | undefined {
  return CATEGORIES.find(c => c.slug === slug || c.id === slug);
}

export function getCategoryProducts(categorySlug: string): CategoryProduct[] {
  const category = getCategoryBySlug(categorySlug);
  return category ? category.products : [];
}

export function searchCategories(query: string): Category[] {
  const q = query.toLowerCase().trim();
  if (!q) return CATEGORIES;
  return CATEGORIES.filter(c =>
    c.name.toLowerCase().includes(q) ||
    c.description.toLowerCase().includes(q) ||
    c.subcategories.some(sub => sub.toLowerCase().includes(q)) ||
    c.products.some(p => p.name.toLowerCase().includes(q) || p.description.toLowerCase().includes(q))
  );
}
